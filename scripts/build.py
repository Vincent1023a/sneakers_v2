"""Build the committed GitHub Pages files from the Markdown wiki."""
import argparse
import json
import re
import sys
from html import escape
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
MARKER = '<!-- Generated by scripts/build.py. Edit wiki/shoes/ instead. -->'
SECTIONS = ('設計特點', '個人實穿紀錄', '相關條目', '參考來源')
REQUIRED = ('title', 'series', 'numeral', 'variant', 'colorway', 'sku', 'summary')
PALETTES = {'ice', 'blue', 'mint', 'sand'}
INLINE = re.compile(r'\[\[([a-z0-9-]+)\]\]|\[([^\]\n]+)\]\((https://[^\s)]+)\)')


def valid_url(value):
    return isinstance(value, str) and value.startswith('https://') and bool(urlsplit(value).hostname)


def load_entries():
    entries = {}
    for path in sorted((ROOT / 'wiki' / 'shoes').glob('*.md')):
        parts = path.read_text(encoding='utf-8').split('---\n', 2)
        if len(parts) != 3 or parts[0]:
            raise ValueError(f'{path.name}：找不到 JSON front matter。')
        metadata = json.loads(parts[1])
        for key in REQUIRED:
            if not isinstance(metadata.get(key), str) or not metadata[key].strip():
                raise ValueError(f'{path.name}：{key} 需要填寫文字。')
        slug = metadata.get('id')
        if slug != path.stem or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', slug):
            raise ValueError(f'{path.name}：id 必須與檔名相同並使用小寫英文、數字與連字號。')
        if type(metadata.get('generation')) is not int or metadata['generation'] < 1:
            raise ValueError(f'{path.name}：generation 必須是正整數。')
        if metadata.get('palette') not in PALETTES:
            raise ValueError(f'{path.name}：palette 需要使用 ice、blue、mint 或 sand。')
        size = metadata.get('size')
        if size is not None and (not isinstance(size, str) or not re.fullmatch(r'US \d+(?:\.5)?', size)):
            raise ValueError(f'{path.name}：size 格式例如 US 11 或 US 10.5，沒有資料填 null。')
        img = metadata.get('image')
        if img is not None:
            if not valid_url(img):
                local = ROOT / img if isinstance(img, str) and re.fullmatch(r'assets/images/[\w.-]+', img) else None
                if not local or not local.is_file():
                    raise ValueError(f'{path.name}：image 需要是 HTTPS 或存在的 assets/images/ 圖片。')
            if not metadata.get('imageCredit') or not valid_url(metadata.get('imageSource')):
                raise ValueError(f'{path.name}：有圖片時需要提供署名與 HTTPS 來源頁。')
        body = parts[2].strip()
        if not body or body.splitlines()[0] != f"# {metadata['title']}":
            raise ValueError(f'{path.name}：H1 需要與 title 相同。')
        headings = re.findall(r'^## (.+)$', body, flags=re.M)
        if headings != list(SECTIONS):
            raise ValueError(f'{path.name}：請依 AGENTS.md 填寫四個章節。')
        metadata['body'] = body.split('\n', 1)[1]
        entries[slug] = metadata
    if not entries:
        raise ValueError('wiki/shoes/ 沒有可發布的條目。')
    return entries


def render_inline(line, entries):
    result = []
    offset = 0
    for match in INLINE.finditer(line):
        result.append(escape(line[offset:match.start()]))
        slug, label, url = match.groups()
        if slug:
            if slug not in entries:
                raise ValueError(f'找不到 Wiki 連結 [[{slug}]]。')
            result.append(f'<a href="./{slug}.html">{escape(entries[slug]["title"])}</a>')
        else:
            if not valid_url(url):
                raise ValueError(f'無效的參考網址 {url}')
            result.append(f'<a href="{escape(url)}">{escape(label)} ↗</a>')
        offset = match.end()
    result.append(escape(line[offset:]))
    return ''.join(result)


def render_body(body, entries):
    chunks = []
    for heading, *lines in (part.strip().splitlines() for part in re.split(r'^## ', body, flags=re.M) if part.strip()):
        rows = []
        bullets = []
        for line in [*lines, '']:
            if line.startswith('- '):
                bullets.append(f'<li>{render_inline(line[2:], entries)}</li>')
                continue
            if bullets:
                rows.append(f'<ul>{"".join(bullets)}</ul>')
                bullets.clear()
            if line.strip():
                rows.append(f'<p>{render_inline(line, entries)}</p>')
        chunks.append(f'<section class="article-section"><h2>{escape(heading)}</h2>{"".join(rows)}</section>')
    return ''.join(chunks)


def layout(title, description, prefix, content, top_link):
    return f'''<!doctype html>
{MARKER}
<html lang="zh-Hant">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="{escape(description)}">
<title>{escape(title)}</title>
<link rel="stylesheet" href="{prefix}assets/styles.css?v=2">
<script src="{prefix}assets/site.js" defer></script>
</head>
<body>
<a class="skip" href="#main">跳到主要內容</a>
<header class="top"><div class="shell top-inner">
<a class="wordmark" href="{prefix}index.html"><span class="mark" aria-hidden="true"><i></i></span> COURT ATLAS</a>
{top_link}
</div></header>
<main id="main" class="shell">{content}</main>
<footer class="shell footer"><a href="{prefix}index.html">COURT ATLAS</a><span>籃球鞋圖鑑 · AI 課程專案</span></footer>
</body>
</html>
'''


def render_plate(shoe, prefix, eager=False):
    visual = ''
    if shoe.get('image'):
        src = shoe['image'] if valid_url(shoe['image']) else prefix + shoe['image']
        loading = 'eager' if eager else 'lazy'
        visual = f'<img src="{escape(src)}" alt="{escape(shoe["title"] + "，" + shoe["colorway"])}" loading="{loading}" decoding="async">'
    return f'''<div class="plate plate-{shoe['palette']}">
<span class="plate-numeral" aria-hidden="true">{escape(shoe['numeral'])}</span>{visual}
</div>'''


def render_home(entries):
    shoes = sorted(entries.values(), key=lambda item: (item['series'].casefold(), item['generation'], item['title'].casefold()))
    series_names = sorted({shoe['series'] for shoe in shoes}, key=str.casefold)
    options = ''.join(f'<option value="{escape(name)}">{escape(name)}</option>' for name in series_names)
    cards = []
    for shoe in shoes:
        search = ' '.join(shoe[key] for key in ('title', 'colorway', 'sku', 'variant', 'summary'))
        search += f" {shoe['series']} {shoe['generation']} {shoe['series']} {shoe['numeral']} {shoe['generation']}代"
        fit = f'<span class="fit-label">{escape(shoe["size"])}</span>' if shoe.get('size') else ''
        cards.append(f'''<li class="card" data-series="{escape(shoe['series'])}" data-search="{escape(search)}">
<a href="./shoes/{shoe['id']}.html" class="card-link">
<div class="card-meta"><span>{escape(shoe['series'])} / 第 {shoe['generation']} 代</span>{fit}</div>
{render_plate(shoe, './')}
<div class="card-body"><h3>{escape(shoe['title'])} <span aria-hidden="true">↗</span></h3>
<p class="colorway"><span>配色</span> {escape(shoe['colorway'])}</p>
<p class="card-summary">{escape(shoe['summary'])}</p></div></a></li>''')
    cover = '<img src="./assets/images/cover.webp" alt="" fetchpriority="high">' if (ROOT / 'assets/images/cover.webp').is_file() else ''
    content = f'''
<section class="hero">
<div class="hero-content">
<h1>籃球鞋<span>圖鑑</span></h1>
<p class="hero-copy">從球場到街頭，按系列查找鞋款配色、設計與實穿紀錄。</p>
<a class="hero-button" href="#catalog">瀏覽鞋款 <span aria-hidden="true">↘</span></a></div>
<div class="hero-court" aria-hidden="true"><div class="court-lines"><i></i><i></i><i></i></div>
<div class="hero-visual">{cover}</div></div>
</section>
<section id="catalog" class="catalog"><div class="catalog-top">
<h2>鞋款索引</h2><div class="scoreboard"><span class="series-total">{len(series_names)} 個系列</span><p id="count" role="status">{len(shoes)} 款球鞋</p></div>
</div>
<div class="filters" hidden>
<label><span>搜尋鞋款</span><input id="search" type="search" placeholder="例如 Kobe IV、Philly、FQ3545-400"></label>
<label><span>系列</span><select id="series"><option value="">所有系列</option>{options}</select></label>
</div>
<ul class="grid">{"".join(cards)}</ul>
<p id="empty" hidden>找不到符合條件的鞋款。<button type="button" id="clear">清除篩選</button></p>
</section>'''
    return layout('籃球鞋圖鑑 | Court Atlas', '按系列與代數瀏覽籃球鞋，了解鞋款設計與實穿尺碼。', './',
                  content, '<a class="top-link" href="#catalog">鞋款索引</a>')


def render_shoe(shoe, entries):
    credit = ''
    if shoe.get('image'):
        credit = f'<figcaption><a href="{escape(shoe["imageSource"])}">{escape(shoe["imageCredit"])} ↗</a></figcaption>'
    specs = [('系列', shoe['series']), ('代數', f"第 {shoe['generation']} 代"), ('版本', shoe['variant']),
             ('款式代碼', shoe['sku']), ('個人實穿尺碼', shoe.get('size') or '待補')]
    terms = ''.join(f'<div><dt>{label}</dt><dd>{escape(value)}</dd></div>' for label, value in specs)
    content = f'''
<nav class="breadcrumb" aria-label="目前位置"><a href="../index.html#catalog">← 鞋款索引</a></nav>
<article>
<div class="detail-head">
<div class="detail-title"><p class="eyebrow"><span></span> {escape(shoe['series'])} / 第 {shoe['generation']} 代</p>
<h1>{escape(shoe['title'])}</h1>
<p class="colorway"><span>配色名稱</span> {escape(shoe['colorway'])}</p>
<p class="detail-summary">{escape(shoe['summary'])}</p>
<dl class="specs">{terms}</dl></div>
<figure>{render_plate(shoe, '../', eager=True)}{credit}</figure>
</div>
<div class="article-body">{render_body(shoe['body'], entries)}</div>
</article>'''
    return layout(f"{shoe['title']} | Court Atlas", shoe['summary'], '../', content,
                  '<a class="top-link" href="../index.html#catalog">鞋款索引</a>')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='驗證 Markdown 和已提交的 HTML 一致')
    args = parser.parse_args()
    entries = load_entries()
    output = {ROOT / 'index.html': render_home(entries)}
    output.update({ROOT / 'shoes' / f'{slug}.html': render_shoe(shoe, entries) for slug, shoe in entries.items()})
    stale = [path for path in (ROOT / 'shoes').glob('*.html') if path not in output and MARKER in path.read_text(encoding='utf-8')]
    if args.check:
        different = [path for path, html in output.items() if not path.exists() or path.read_text(encoding='utf-8') != html]
        if stale or different:
            raise ValueError('請執行建置以同步 HTML：' + '、'.join(str(path.relative_to(ROOT)) for path in different + stale))
        print(f'已驗證 {len(entries)} 篇 Wiki 條目及 {len(output)} 個頁面。')
        return
    (ROOT / 'shoes').mkdir(exist_ok=True)
    for path, html in output.items():
        path.write_text(html, encoding='utf-8')
    for path in stale:
        path.unlink()
    print(f'已從 {len(entries)} 篇 Wiki 條目產生 {len(output)} 個頁面。')


if __name__ == '__main__':
    try:
        main()
    except ValueError as exc:
        sys.exit(str(exc))
